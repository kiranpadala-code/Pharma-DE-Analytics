--Automated each month batch record count query;
USE WAREHOUSE PHARMA_WH;
USE DATABASE PHARMA_DB;
USE SCHEMA RAW;

SET BATCH_MONTH = '2026-01';

WITH expected AS (
    SELECT
        SPLIT_PART($1, '/', -1) AS FILE_NAME,
        UPPER($2) AS DATASET,
        $3 AS LOAD_MONTH,
        $4::NUMBER AS EXPECTED_COUNT
    FROM @PHARMA_STAGE/metadata/manifest.csv
    WHERE $3 <= $BATCH_MONTH
       OR $3 IS NULL
       OR $3 = ''
),

actual_records AS (
    SELECT 'PRODUCT' AS DATASET, _SOURCE_FILE FROM PRODUCT
    UNION ALL
    SELECT 'TERRITORY', _SOURCE_FILE FROM TERRITORY
    UNION ALL
    SELECT 'SPECIALTY_PRODUCT_MAP', _SOURCE_FILE FROM SPECIALTY_PRODUCT_MAP
    UNION ALL
    SELECT 'ACCOUNT_MASTER', _SOURCE_FILE FROM ACCOUNT_MASTER
    UNION ALL
    SELECT 'HCP_MASTER', _SOURCE_FILE FROM HCP_MASTER
    UNION ALL
    SELECT 'ROSTER', _SOURCE_FILE FROM ROSTER
    UNION ALL
    SELECT 'XPONENT', _SOURCE_FILE FROM XPONENT
    UNION ALL
    SELECT 'CALLS_INTERACTIONS', _SOURCE_FILE FROM CALLS_INTERACTIONS
    UNION ALL
    SELECT 'SAMPLES', _SOURCE_FILE FROM SAMPLES
),

actual AS (
    SELECT
        DATASET,
        SPLIT_PART(_SOURCE_FILE, '/', -1) AS FILE_NAME,
        COUNT(*) AS ACTUAL_COUNT
    FROM actual_records
    GROUP BY 1, 2
)

SELECT
    COALESCE(e.DATASET, a.DATASET) AS DATASET,
    COALESCE(e.FILE_NAME, a.FILE_NAME) AS FILE_NAME,
    e.EXPECTED_COUNT,
    COALESCE(a.ACTUAL_COUNT, 0) AS ACTUAL_COUNT,
    COALESCE(a.ACTUAL_COUNT, 0) -
        COALESCE(e.EXPECTED_COUNT, 0) AS DIFFERENCE,
    CASE
        WHEN e.FILE_NAME IS NULL THEN 'UNEXPECTED FILE'
        WHEN a.FILE_NAME IS NULL THEN 'MISSING FILE'
        WHEN e.EXPECTED_COUNT = a.ACTUAL_COUNT THEN 'PASS'
        ELSE 'FAIL'
    END AS STATUS
FROM expected e
FULL OUTER JOIN actual a
    ON e.DATASET = a.DATASET
    AND e.FILE_NAME = a.FILE_NAME
ORDER BY DATASET, FILE_NAME;